-- Schema Supabase untuk Monitoring Inflasi IHK Kalbar (6100)
-- Jalankan SQL ini di Supabase SQL Editor apabila tabel belum tersedia.

create table if not exists public.inflasi_lk_data (
  id bigint generated by default as identity primary key,
  tahun integer not null,
  bulan integer not null check (bulan between 1 and 12),
  kode_wilayah text not null,
  kode_komoditas text not null,
  nk0 numeric not null default 0,
  nk_n1 numeric not null default 0,
  rh_n numeric not null default 100,
  updated_at timestamptz not null default now(),
  constraint inflasi_lk_data_unique_key unique (tahun, bulan, kode_wilayah, kode_komoditas)
);

create index if not exists idx_inflasi_lk_data_period_region
  on public.inflasi_lk_data (tahun, bulan, kode_wilayah);

create table if not exists public.inflasi_upload_logs (
  id bigint generated by default as identity primary key,
  tahun integer not null,
  bulan integer not null check (bulan between 1 and 12),
  kode_wilayah text not null,
  jenis_upload text not null,
  nama_file text not null,
  matched_count integer not null default 0,
  unmatched_count integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_inflasi_upload_logs_period
  on public.inflasi_upload_logs (tahun, bulan, created_at desc);

create table if not exists public.inflasi_harga_responden (
  id bigint generated by default as identity primary key,
  tahun integer not null,
  bulan integer not null check (bulan between 1 and 12),
  kode_wilayah text not null,
  frekuensi text not null check (frekuensi in ('MINGGUAN', 'DWIMINGGUAN', 'BULANAN')),
  obs_key text not null,
  kode_komoditas text not null,
  komoditas text not null,
  kode_kualitas text not null default '',
  bobot_kualitas numeric not null default 0,
  kualitas text not null default '',
  bobot_jenis_pasar numeric not null default 0,
  jenis_pasar text not null default '',
  bobot_pasar numeric not null default 0,
  pasar text not null default '',
  nama_responden text not null default '',
  prev_prices jsonb not null default '[]'::jsonb,
  curr_prices jsonb not null default '[]'::jsonb,
  prev_avg_price numeric,
  curr_avg_price numeric,
  price_relative numeric,
  file_name text,
  updated_at timestamptz not null default now(),
  constraint inflasi_harga_responden_unique_key unique (tahun, bulan, kode_wilayah, frekuensi, obs_key)
);

create index if not exists idx_inflasi_harga_responden_period_region
  on public.inflasi_harga_responden (tahun, bulan, kode_wilayah, frekuensi);

-- RLS Policies (Sesuaikan jika menggunakan autentikasi Supabase Auth)
alter table public.inflasi_lk_data enable row level security;
alter table public.inflasi_upload_logs enable row level security;
alter table public.inflasi_harga_responden enable row level security;

drop policy if exists "Allow anon all inflasi_lk_data" on public.inflasi_lk_data;
create policy "Allow anon all inflasi_lk_data"
  on public.inflasi_lk_data for all to anon, authenticated
  using (true) with check (true);

drop policy if exists "Allow anon all inflasi_upload_logs" on public.inflasi_upload_logs;
create policy "Allow anon all inflasi_upload_logs"
  on public.inflasi_upload_logs for all to anon, authenticated
  using (true) with check (true);

drop policy if exists "Allow anon all inflasi_harga_responden" on public.inflasi_harga_responden;
create policy "Allow anon all inflasi_harga_responden"
  on public.inflasi_harga_responden for all to anon, authenticated
  using (true) with check (true);
